// Seeded pseudo-random generator for deterministic data
function seededRandom(seed: number): () => number {
  let s = seed;
  return () => {
    s = (s * 9301 + 49297) % 233280;
    return s / 233280;
  };
}

function generateHistory(basePrice: number, seed: number, points = 30): number[] {
  const rng = seededRandom(seed);
  const history: number[] = [];
  let price = basePrice * (0.8 + rng() * 0.2);
  for (let i = 0; i < points; i++) {
    price *= 1 + (rng() - 0.48) * 0.06;
    history.push(Math.round(price * 100) / 100);
  }
  return history;
}

