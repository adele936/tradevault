function buildAssets(): Asset[] {
  const assets: Asset[] = [];
  const seenSymbols = new Set<string>();

  STOCK_DATA.forEach((row, idx) => {
    const [symbol, name, basePrice, sector] = row;
    const key = `stock-${symbol}`;
    if (seenSymbols.has(key)) return;
    seenSymbols.add(key);
    const rng = seededRandom(idx * 1000 + 1);
    const changePercent = (rng() - 0.45) * 8;
    const change = (basePrice * changePercent) / 100;
    const volume = Math.floor(rng() * 50_000_000) + 1_000_000;
    const marketCap = basePrice * (Math.floor(rng() * 5_000_000_000) + 100_000_000);
    const history = generateHistory(basePrice, idx * 1000 + 1);
    assets.push({
      symbol,
      name,
      price: Math.round((basePrice + change) * 100) / 100,
      change: Math.round(change * 100) / 100,
      changePercent: Math.round(changePercent * 100) / 100,
      volume,
      marketCap,
      type: 'stock',
      sector,
      history,
    });
  });

  CRYPTO_DATA.forEach((row, idx) => {
    const [symbol, name, basePrice] = row;
    const key = `crypto-${symbol}`;
    if (seenSymbols.has(key)) return;
    seenSymbols.add(key);
    const rng = seededRandom((idx + 500) * 1000 + 1);
    const changePercent = (rng() - 0.45) * 12;
    const change = (basePrice * changePercent) / 100;
    const volume = Math.floor(rng() * 10_000_000_000) + 100_000_000;
    const marketCap = basePrice * (Math.floor(rng() * 500_000_000) + 10_000_000);
    const history = generateHistory(basePrice, (idx + 500) * 1000 + 1);
    assets.push({
      symbol,
      name,
      price: Math.round((basePrice + change) * 1000000) / 1000000,
      change: Math.round(change * 1000000) / 1000000,
      changePercent: Math.round(changePercent * 100) / 100,
      volume,
      marketCap,
      type: 'crypto',
      history,
    });
  });

  return assets;
}

let cachedAssets: Asset[] | null = null;

export function getAllAssets(): Asset[] {
  if (!cachedAssets) {
    cachedAssets = buildAssets();
  }
  return cachedAssets;
}

export function getStocks(): Asset[] {
  return getAllAssets().filter((a) => a.type === 'stock');
}

export function getCrypto(): Asset[] {
  return getAllAssets().filter((a) => a.type === 'crypto');
}

export function getTopGainers(count = 10): Asset[] {
  return [...getAllAssets()].sort((a, b) => b.changePercent - a.changePercent).slice(0, count);
}

export function getTopLosers(count = 10): Asset[] {
  return [...getAllAssets()].sort((a, b) => a.changePercent - a.changePercent).slice(0, count);
}

export function getMostActive(count = 10): Asset[] {
  return [...getAllAssets()].sort((a, b) => b.volume - a.volume).slice(0, count);
}

export function getAssetBySymbol(symbol: string): Asset | undefined {
  return getAllAssets().find((a) => a.symbol === symbol);
}

export function formatCurrency(value: number): string {
  if (value >= 1_000_000_000_000) return `$${(value / 1_000_000_000_000).toFixed(2)}T`;
  if (value >= 1_000_000_000) return `$${(value / 1_000_000_000).toFixed(2)}B`;
  if (value >= 1_000_000) return `$${(value / 1_000_000).toFixed(2)}M`;
  if (value >= 1_000) return `$${(value / 1_000).toFixed(2)}K`;
  return `$${value.toFixed(2)}`;
}

export function formatPrice(value: number): string {
  if (value < 0.01) return `$${value.toFixed(8)}`;
  if (value < 1) return `$${value.toFixed(4)}`;
  return `$${value.toFixed(2)}`;
}

export function formatVolume(value: number): string {
  if (value >= 1_000_000_000) return `${(value / 1_000_000_000).toFixed(2)}B`;
  if (value >= 1_000_000) return `${(value / 1_000_000).toFixed(2)}M`;
  if (value >= 1_000) return `${(value / 1_000).toFixed(2)}K`;
  return value.toString();
}
